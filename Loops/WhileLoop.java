package Loops;

public class WhileLoop {
    public static void main(String[] args){
        int i = 0;
        while (i <= 10) {
            System.out.print(i + " ");
            i++;
        }
    }
}

//the reason you may want to use a while loop is because 
//you want to repeat a certain operation a number of times, but you don't know exactly
//how many times. What matters more is the specific condition you want fulfilled